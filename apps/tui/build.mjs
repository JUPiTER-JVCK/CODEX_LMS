// Bundle the terminal app into one file: apps/tui/dist/codex-tui.mjs (Node 18+, no dependencies at run time).
import { build } from "esbuild";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const out = path.join(here, "dist/codex-tui.mjs");
await build({
  entryPoints: [path.join(here, "src/cli.ts")],
  outfile: out,
  bundle: true,
  format: "esm",
  platform: "node",
  target: "node18",
  legalComments: "none",
  banner: { js: "#!/usr/bin/env node\n// CODEX_LMS terminal app. GENERATED by apps/tui (npm run tui:build). Needs Node 18+ and the built page (dist/index.html) beside it or passed with --book." },
});
fs.chmodSync(out, 0o755);
console.log(`wrote ${path.relative(process.cwd(), out)} (${(fs.statSync(out).size / 1024).toFixed(0)} KB)`);
