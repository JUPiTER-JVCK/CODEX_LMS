// Bundle the lab views (and the widget logic they import) into one classic <script>: src/ws-5-labs.js.
import { build } from "esbuild";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
await build({
  entryPoints: [path.join(here, "src/index.ts")],
  outfile: path.join(here, "../../src/ws-5-labs.js"),
  bundle: true,
  format: "iife",
  target: "es2019",
  minify: false,
  legalComments: "none",
  banner: { js: "/* GENERATED by packages/labs (npm run labs). Edit packages/labs/src and packages/widgets/src, not this file. */" },
});
console.log("wrote src/ws-5-labs.js");
