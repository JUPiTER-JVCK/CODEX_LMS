#!/usr/bin/env python3
"""Bake Wireshark's own Source/Destination/Protocol/Info columns for every lab scenario into src/ws-6-pcapcols.js.

Run after tools/pcapgen.js whenever src/ws-5-pcap.js changes. Needs tshark."""
import json, os, subprocess, glob
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
cols = {}
ver = subprocess.run(['tshark', '-v'], capture_output=True, text=True).stdout.split('\n')[0]
for p in sorted(glob.glob(os.path.join(ROOT, 'test/pcaps/*.pcap'))):
    sid = os.path.basename(p)[:-5]
    out = subprocess.run(['tshark', '-r', p, '-2', '-T', 'fields', '-E', 'separator=\t', '-e', 'frame.number', '-e', '_ws.col.def_src',
                          '-e', '_ws.col.def_dst', '-e', '_ws.col.protocol', '-e', '_ws.col.info'], capture_output=True, text=True).stdout
    rows = []
    for line in out.strip('\n').split('\n'):
        n, src, dst, proto, info = line.split('\t')
        rows.append([src, dst, proto, info.rstrip()])
    cols[sid] = rows
with open(os.path.join(ROOT, 'src/ws-6-pcapcols.js'), 'w') as f:
    f.write('/* Generated by tools/pcapcols.py from ' + ver + ': the Source, Destination, Protocol and Info columns for each lab capture. */\n')
    f.write('window.__pcapCols = ' + json.dumps(cols, separators=(',', ':')) + ';\n')
print('wrote src/ws-6-pcapcols.js', {k: len(v) for k, v in cols.items()})
